"""SUPERVISORY_REPAIR_REPORT.md: issue / root cause / change / tests / numerical effect, v1 baseline vs current.
All numbers are read from outputs/baseline_v1/ (frozen before the second pass) and the current outputs."""
from __future__ import annotations

import json

import numpy as np
import pandas as pd


def _p(x, nd=0):
    return f"{x * 100:.{nd}f}%" if pd.notna(x) else "n/a"


def _m(x):
    return f"RUB {x / 1e6:.2f}m" if pd.notna(x) else "n/a"


def write(ctx) -> None:
    o, b = ctx.out, ctx.out / "baseline_v1"
    v1 = json.loads((b / "key_findings.json").read_text())
    v2 = json.loads((o / "key_findings.json").read_text())
    fd = pd.read_csv(o / "factor_decomposition.csv").set_index("window")
    cc = pd.read_csv(o / "collateral_conclusions.csv")
    spec = pd.read_csv(o / "futures_contract_spec_audit.csv")
    u1 = pd.read_csv(b / "instrument_universe.csv").set_index("id")
    u2 = pd.read_csv(o / "instrument_universe.csv").set_index("id")
    ba = pd.read_csv(o / "fhs_basis_audit.csv")
    bs1 = pd.read_csv(b / "bootstrap_strategy_metrics.csv")
    bs2 = pd.read_csv(o / "bootstrap_strategy_metrics.csv")
    L = ["# Supervisory repair report (second research pass)", "",
         "**Scope.** Items A1-A7 from the supervisory review, plus two further defects found during this pass (A7b, A7c).",
         "",
         "**Numbers.** Every number is generated by `smlt_hedge.reporting.repair_report` from the frozen v1 outputs "
         "(`outputs/baseline_v1/`) and the current pipeline outputs.", ""]

    # A1
    full, l250 = fd.loc["FULL"], fd.loc["LAST_250D"]
    L += ["## A1 — \"67% issuer-specific\" claim", "",
          "**Issue.** v1 labelled 1 − corr(SMLT, MIX)² as *issuer-specific* risk.", "",
          "**Root cause.** A single-factor residual was interpreted as an economic category.", "",
          "**Change.** The residual is now reported only as *variance unexplained by the broad-market factor*. An explicit four-factor model was added (`features/factors.py`):",
          "- market: IMOEX;",
          "- sector: equal-weight peers **excluding** SMLT (MOEXRE contains SMLT, so it is circular);",
          "- rates: RGBI return (duration-consistent);",
          "- credit: Samolet bond excess return over OFZ, duration-matched.",
          "",
          "It uses Shapley variance shares and Newey-West t-statistics. The MOEX Z-spread variant exists only from Dec 2025 and is reported as a robustness row.", "",
          "**Tests added.** `test_shapley_shares_sum_to_total_r2`, `test_rolling_factor_loadings_have_no_lookahead`.", "",
          "**Numerical effect.**",
          f"- v1 text: {v1.get('idio_share_vs_index')} \"issuer-specific\".",
          f"- Market alone explains {_p(full['v1_single_factor_market_R2'])} (full sample) and {_p(l250['v1_single_factor_market_R2'])} (250d).",
          f"- The four-factor model explains {_p(full['total_R2'])} (full) and {_p(l250['total_R2'])} (250d).",
          f"- Shapley shares, full sample: market {_p(full['shapley_MKT'])}, sector {_p(full['shapley_SECTOR'])}, rates {_p(full['shapley_RATES'])}, credit {_p(full['shapley_CREDIT'])}.",
          f"- Unexplained: {_p(full['unexplained'])} full, {_p(l250['unexplained'])} last 250d.",
          "",
          "**Conclusion changed?** The *label* changed: the \"issuer-specific\" claim is withdrawn. The hedging conclusion did not change: sector (not tradable) and residual risk still require SMLT itself.",
          "",
          "**Limitation.** The credit factor is issuer-own and endogenous, and loadings are unstable across years (see `factor_decomposition.csv`).", ""]

    # A2
    def cl(v, hz, name):
        r = cc[(cc["variant"] == v) & (cc["horizon"] == hz) & (cc["capital"] == ctx.C) & (cc["collateral"] == name)]
        return r.iloc[0] if len(r) else None
    L += ["## A2 — Collateral / liquidity regimes", "",
          "**Issue.** v1 used one collateral assumption: margin cash earns 0.", "",
          "**Change.** `strategies/collateral.py` defines generic regimes (no broker selected), shared by the contract simulator, the bootstrap engine and the deterministic engine. Parameters:",
          "- `yield_fraction`: share of posted IM that stays productive (earns money-market carry);",
          "- `haircut`: haircut on productive collateral (consumes extra capital);",
          "- `margin_multiplier`: broker add-on over the NCC rate.",
          "",
          "Tested grid: yield fraction 0 / 0.5 / 1 × multiplier 1.0 / 1.25 / 1.5 (haircut 10% when productive), plus named regimes A, B and C.", "",
          "**Tests added.** `test_collateral_regime_accounting`, `test_productive_collateral_earns_carry`.", "",
          "**Numerical effect** (capital RUB 10m; `collateral_conclusions.csv`):", "",
          "| model / horizon | regime | sell dominates futures (same fraction) | best futures ratio with breach ≤ 20% | breach FUT_50 / 75 / 100 |",
          "|---|---|---|---|---|"]
    for v in ("FHS_FULL", "HS_FULL"):
        for hz in ("6m", "12m"):
            for name in ("A_CASH_ONLY_CONSERVATIVE", "B_PARTIALLY_PRODUCTIVE", "C_HIGH_COLLATERAL_EFFICIENCY", "yf0.00_hc0.00_mm1.50"):
                r = cl(v, hz, name)
                if r is None:
                    continue
                L.append(f"| {v} {hz} | {name} | {r['sell_dominates_fut_same_fraction']} | {r['best_fut_breach_le_20pct']} | "
                         f"{_p(r['breach_FUT_50'])} / {_p(r['breach_FUT_75'])} / {_p(r['breach_FUT_100'])} |")
    L += ["", "**Conclusions changed?**", "",
          "- **\"Selling dominates futures\"** holds in the cash-only and partially productive regimes. It **weakens or fails in the high-collateral-efficiency regime** under FHS: once margin earns carry, only the smaller 12.1% vs 14.8% carry gap remains. This v1 statement is now conditional on collateral mechanics.",
          "- **\"50% is preferable to 75/100%\"** (on liquidity) survives every regime. The breach ranking is driven by VM and IM consumption, which collateral yield does not change. A broker multiplier of 1.5 moves every breach probability up. Under FHS, 50% is at the 20% breach boundary and 25% is the conservative choice.", ""]

    # A3
    L += ["## A3 — Exact futures accounting in headline metrics", "",
          "**Issue.** v1 headline numbers used h × (spot exposure) as the futures notional and closed-form shortcuts.", "",
          "**Change.**",
          "- `strategies/futures.py` gained `contract_position` (contracts = round(h × shares / lot); notional = contracts × settle × point value) and `engine_jump_state` / `rally_exhausting_sleeve`: a bisection on the SAME daily contract simulator used in the backtest.",
          "- The bootstrap, deterministic and collateral engines use the exact notional.",
          "- Every headline threshold in `key_findings.json` is now produced by these functions.",
          "",
          "**Tests added.** `test_exact_contract_notional_uses_futures_settle_not_spot`, `test_headline_rally_trigger_equals_engine_and_closed_form`, `test_report_numbers_equal_engine`.", "",
          "**Numerical effect.**",
          f"- Full-hedge IM: v1 RUB {v1.get('im_full')}m → v2 RUB {v2.get('im_full')}m ({v2.get('full_contracts')} contracts × settle).",
          f"- 50% hedge: {v2.get('rec_contracts')} contracts, notional RUB {v2.get('rec_notional')}m, IM RUB {v2.get('rec_im')}m.",
          f"- Rally that exhausts the RUB 10m sleeve at 50%: v1 {v1.get('rec_xstar')} → v2 {v2.get('rec_xstar')}.",
          f"- Margin-rule trigger: v1 {v1.get('rec_trigger_rally')} → v2 {v2.get('rec_trigger_rally')}.",
          f"- Full hedge exhausted at a rally of v2 {v2.get('xstar_full_10m')} (v1 {v1.get('cap_fhs_6m_10p0_xstar')}).",
          "",
          "**Conclusion changed?** The direction is unchanged. Thresholds are 2-4 pp tighter because the futures trade at a premium (F0/S0 ≈ 1.03).", ""]

    # A4
    L += ["## A4 — Futures traded value and contract specifications", "",
          "**Issue.** v1 computed futures traded value as VOLUME × SETTLE for every family.", "",
          "**Change.**",
          "- `data/specs.py` derives the point value (STEPPRICE / MINSTEP) for each family and checks it against the exchange-reported RUB VALUE.",
          "- Liquidity now uses the exchange VALUE (correct for any unit).",
          "- G4 was regenerated.",
          "",
          "**Numerical effect.** v1 formula error factor (exchange value / (volume × settle)):", "",
          spec[["instrument", "contract", "point_value", "notional_rub_at_snapshot", "exchange_value_over_vol_settle_median_120d",
                "fx_linked_point_value", "verified"]].to_markdown(index=False, floatfmt=".3f"), ""]
    ch = []
    for i in u2.index:
        same = lambda a, b: (pd.isna(a) and pd.isna(b)) or a == b  # noqa: E731
        if i in u1.index and not (same(u1.loc[i, "classification"], u2.loc[i, "classification"])
                                  and same(u1.loc[i, "G4_liquidity"], u2.loc[i, "G4_liquidity"])):
            ch.append({"id": i, "v1_G4": u1.loc[i, "G4_liquidity"], "v2_G4": u2.loc[i, "G4_liquidity"],
                       "v1_class": u1.loc[i, "classification"], "v2_class": u2.loc[i, "classification"]})
    L += ["Classification / G4 changes v1 → v2:", "",
          pd.DataFrame(ch).to_markdown(index=False) if ch else "_none_", "",
          "**Conclusion changed?** v1 had understated liquidity for CNY (×1000), IMOEXF/MXI (×10), Brent (≈×800) and gold (≈×80). "
          "Those instruments already passed G4, so no admission decision reversed. New or changed rows above come from A5 and A6.", ""]

    # A5, A6
    def urow(i):
        return u2.loc[i] if i in u2.index else None
    sb, ss, ho = urow("SMLT_BONDS"), urow("SMLT_BOND_SHORT"), urow("HOME_FUT")
    L += ["## A5 — Samolet bond classification", "",
          "**Issue.** v1 said SMLT_BONDS failed G1 (\"no price\") while the dossier listed bonds traded on the decision date.", "",
          "**Root cause.** The bond candidate had no series attached, so the generic price check failed.", "",
          "**Change.**",
          "- A constant-composition Samolet bond index (`SMLT_BOND_IDX`) and the traded-value evidence were added.",
          f"- LONG bonds: G1 {sb['G1_existence'] if sb is not None else 'n/a'}, classification {sb['classification'] if sb is not None else 'n/a'} (same issuer, not a hedge).",
          f"- SHORT bonds (credit hedge via lending or repo): {ss['classification'] if ss is not None else 'n/a'}. The reason: {ss['reasons'] if ss is not None else ''}",
          "",
          f"**Evidence.** Correlation of the bond index with SMLT: {ss['corr_250d']:.2f} (250d); h* {ss['hstar_250d']:.2f}." if ss is not None else "", "",
          "## A6 — Housing (HOME) futures", "",
          "**Change.** MOEX HOME futures (Domclick Moscow housing index / 10, cash-settled, 2023→) were fetched, spec-verified and screened.", "",
          f"**Result.** {ho['classification'] if ho is not None else 'n/a'}: {ho['reasons'] if ho is not None else ''}", ""]

    # A7 (+ b, c)
    g = lambda s, mtr, c="historical": ba[(ba.section == s) & (ba.metric == mtr)][c].iloc[0]  # noqa: E731
    def es(bs, v, hz, st):
        r = bs[(bs["variant"] == v) & (bs["horizon"] == hz) & (bs["capital"] == ctx.C) & (bs["strategy"] == st)]
        return float(r["ES95"].iloc[0]) if len(r) else np.nan
    L += ["## A7 — FHS / basis red-team", "",
          "See FHS_BASIS_AUDIT.md.",
          f"- The repaired structural-basis model matches the historical basis residual: std {g('residual', 'basis residual std', 'simulated'):.4f} simulated vs {g('residual', 'basis residual std'):.4f} historical.",
          f"- Lag-1 autocorrelation {g('residual', 'basis residual lag-1 autocorr', 'simulated'):.2f} vs {g('residual', 'basis residual lag-1 autocorr'):.2f}.",
          f"- It is not a copy of spot: daily corr {g('comovement', 'daily corr(spot, fut) full sample', 'simulated'):.3f}.",
          "- A 2022-type basis-dislocation stress (residual × 2 / × 3) was added.", "",
          "**A7b — FHS scaled simple returns (new defect found in this pass).** Rescaling the 2022 invasion day (a ~20σ shock at low prior volatility) to current volatility in simple-return space produced returns below −100%. That meant negative prices and an ES larger than the position. FHS now works in log-return space (test `test_fhs_never_produces_returns_below_minus_100pct`).", "",
          "**A7c — Inconsistent bootstrap samples (new defect).** The sample start depended on which columns a stage used, so the collateral stage included the invasion days while stage 8 did not. One common joint sample start (2022-03-28, the first day every Phase-B series exists) is now set in config for all stages. Invasion-type jumps are covered by the deterministic event overlays.", "",
          "**Numerical effect on the decision-date bootstrap** (capital RUB 10m, ES95):", "",
          "| strategy | FHS 6m v1 | FHS 6m v2 | HS 6m v1 | HS 6m v2 |", "|---|---|---|---|---|"]
    for st in ("CONTROL", "FUT_25", "FUT_50", "FUT_75", "FUT_100", "DERISK_SELL_50"):
        L.append(f"| {st} | {_m(es(bs1, 'FHS_FULL', '6m', st))} | {_m(es(bs2, 'FHS_FULL', '6m', st))} | "
                 f"{_m(es(bs1, 'HS_FULL', '6m', st))} | {_m(es(bs2, 'HS_FULL', '6m', st))} |")
    L += ["", "**Conclusions changed?** Levels moved (exact notional, log-FHS, common sample). The ordering of strategies and the "
          "liquidity findings did not.", "",
          "## A8 — Primary sources", "",
          "- Bank of Russia, e-disclosure and ACRA are still unreachable from this environment (HTTP 403 or timeout on 2026-09-28).",
          "- The owner-run fetchers are unchanged; the commands are in README.md.",
          "- PRIMARY_SOURCE_DELTA.md cannot be produced until those files exist.", ""]
    (ctx.root / "SUPERVISORY_REPAIR_REPORT.md").write_text("\n".join(L))
